import puppeteer from "puppeteer-core";
const out = process.argv[2];
const browser = await puppeteer.launch({ executablePath: "/usr/bin/google-chrome", headless: true, args: ["--no-sandbox", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"], defaultViewport: { width: 1280, height: 800 } });
const page = await browser.newPage();
page.on("pageerror", (e) => console.log("[pageerror]", e.message));
await page.goto("http://localhost:5173/?map=Farm&x=60&y=20&time=900");
await new Promise((r) => setTimeout(r, 5000));
const spot = (await page.evaluate(`(() => {
  const w = window.__game.scene.getScene("World");
  const ok = function (tx, ty) { const b = w.location.tileProps("Back", tx, ty); return !!b && "Diggable" in b && !w.occupied(tx, ty) && !w.location.blocksFarmer(tx, ty); };
  const clear = function (x, y) { for (let dy = -1; dy <= 2; dy++) for (let dx = -1; dx <= 2; dx++) if (!ok(x + dx, y + dy)) return false; return true; };
  for (let y = 10; y < 60; y++) for (let x = 10; x < 75; x++) if (clear(x, y)) return { x, y };
  return null;
})()`)) as { x: number; y: number } | null;
console.log("spot", JSON.stringify(spot));
await page.goto(`http://localhost:5173/?map=Farm&x=${spot!.x}&y=${spot!.y}&time=900`);
await new Promise((r) => setTimeout(r, 5000));
await page.keyboard.press("2");
await page.keyboard.down("c");
await new Promise((r) => setTimeout(r, 120));
await page.screenshot({ path: `${out}/swing1.png` });
await page.keyboard.up("c");
await new Promise((r) => setTimeout(r, 900));
for (let i = 0; i < 0; i++) { console.log("t", await page.evaluate(`(() => { const w = window.__game.scene.getScene("World"); return JSON.stringify({ i: w.tool && w.tool.anim.index, timer: w.tool && w.tool.anim.timer, ticks: w.ticks, acc: w.accumulator, warping: w.warping, fps: window.__game.loop.actualFps }); })()`)); await new Promise((r) => setTimeout(r, 300)); }
console.log("after first", await page.evaluate(`(() => { const w = window.__game.scene.getScene("World"); return JSON.stringify({ tool: w.tool && { index: w.tool.anim.index, done: w.tool.anim.done, frames: w.tool.anim.frames.length }, q: !!(w.question && w.question.open) }); })()`));
await page.keyboard.down("d");
await new Promise((r) => setTimeout(r, 60));
await page.keyboard.up("d");
await page.keyboard.press("c");
await new Promise((r) => setTimeout(r, 900));
await page.keyboard.down("s");
await new Promise((r) => setTimeout(r, 60));
await page.keyboard.up("s");
await page.keyboard.press("c");
await new Promise((r) => setTimeout(r, 900));
await page.keyboard.press("3");
await page.keyboard.press("c");
await new Promise((r) => setTimeout(r, 300));
await page.screenshot({ path: `${out}/water.png` });
await new Promise((r) => setTimeout(r, 1200));
await page.screenshot({ path: `${out}/after.png` });
console.log(await page.evaluate(`(() => { const w = window.__game.scene.getScene("World"); return JSON.stringify({ dirt: w.entities.filter(function (e) { return e.kind === "hoeDirt"; }), stamina: w.params.state.stamina, water: w.params.state.waterLeft }); })()`));
await browser.close();
