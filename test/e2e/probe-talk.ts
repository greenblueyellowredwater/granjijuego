import puppeteer from "puppeteer-core";
const out = process.argv[2];
const browser = await puppeteer.launch({ executablePath: "/usr/bin/google-chrome", headless: true, args: ["--no-sandbox", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"], defaultViewport: { width: 1280, height: 800 } });
const page = await browser.newPage();
page.on("pageerror", (e) => console.log("[pageerror]", e.message));
const wait = (ms: number) => new Promise((r) => setTimeout(r, ms));
const world = (expr: string) => page.evaluate(`(() => { const w = window.__game.scene.getScene("World"); return ${expr}; })()`);
await page.goto("http://localhost:5173/?map=Town&x=43&y=60&time=600");
await page.evaluate(`localStorage.clear()`);
await page.goto("http://localhost:5173/?map=SeedShop&x=4&y=21&time=600");
await wait(6000);
const where = await world(`(function () { const n = w.params.npcs.in("SeedShop").find(function (n) { return n.name === "Pierre"; }); return n && { x: Math.round(n.x / 64), y: Math.round(n.y / 64), walking: n.walking }; })()`) as { x: number; y: number };
console.log("pierre", JSON.stringify(where));
await world(`(function () { w.body.x = ${where.x} * 64; w.body.y = (${where.y} + 1) * 64 + 16; w.body.facing = 0; return 1; })()`);
await wait(300);
await page.keyboard.press("x");
await wait(1500);
await page.screenshot({ path: `${out}/talk1.png` });
await page.keyboard.press("x");
await wait(1500);
await page.screenshot({ path: `${out}/talk2.png` });
await page.keyboard.press("x"); await wait(300); await page.keyboard.press("x"); await wait(300);
console.log(await world(`JSON.stringify({ open: w.dialogueBox.open, f: w.params.state.friendship })`));
await browser.close();
